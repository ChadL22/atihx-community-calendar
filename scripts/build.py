#!/usr/bin/env python3
"""Build script for the ATIHx Community Calendar.

Reads data/events.json (the single source of truth) and writes:
  - data/events.js        the same data as a JS file, so index.html works
                          even when opened straight from your computer
  - calendars/all.ics     subscribable feed with every community
  - calendars/<id>.ics    one feed per community (e.g. philly.ics, dc.ics)
  - calendars/<a>+<b>.ics feeds for each combination of communities

Run it from the project folder after editing data/events.json:

    python3 scripts/build.py

Uses only the Python standard library.
"""

import itertools
import json
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "events.json"
CAL_DIR = ROOT / "calendars"

VTIMEZONE_NY = """BEGIN:VTIMEZONE
TZID:America/New_York
BEGIN:DAYLIGHT
TZOFFSETFROM:-0500
TZOFFSETTO:-0400
TZNAME:EDT
DTSTART:19700308T020000
RRULE:FREQ=YEARLY;BYMONTH=3;BYDAY=2SU
END:DAYLIGHT
BEGIN:STANDARD
TZOFFSETFROM:-0400
TZOFFSETTO:-0500
TZNAME:EST
DTSTART:19701101T020000
RRULE:FREQ=YEARLY;BYMONTH=11;BYDAY=1SU
END:STANDARD
END:VTIMEZONE"""


def ics_escape(text):
    return (
        str(text)
        .replace("\\", "\\\\")
        .replace(";", "\\;")
        .replace(",", "\\,")
        .replace("\n", "\\n")
    )


def fold(line):
    """Fold long lines to 75 octets as the iCalendar spec requires."""
    out, raw = [], line.encode("utf-8")
    while len(raw) > 75:
        cut = 75
        while (raw[cut] & 0xC0) == 0x80:  # don't split a UTF-8 character
            cut -= 1
        out.append(raw[:cut].decode("utf-8"))
        raw = b" " + raw[cut:]
    out.append(raw.decode("utf-8"))
    return "\r\n".join(out)


def local_stamp(value):
    """'2026-10-13T18:00' -> '20261013T180000'"""
    return datetime.fromisoformat(value).strftime("%Y%m%dT%H%M%S")


def build_ics(name, events, communities):
    now = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    lines = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        "PRODID:-//ATIHx Community Calendar//EN",
        "CALSCALE:GREGORIAN",
        "METHOD:PUBLISH",
        f"X-WR-CALNAME:{ics_escape(name)}",
        "X-WR-TIMEZONE:America/New_York",
        "REFRESH-INTERVAL;VALUE=DURATION:PT6H",
        "X-PUBLISHED-TTL:PT6H",
    ]
    lines += VTIMEZONE_NY.split("\n")
    for ev in events:
        community = communities[ev["community"]]
        tz = ev.get("timezone", "America/New_York")
        location = ev.get("venue", "")
        if ev.get("address"):
            location = f"{location}, {ev['address']}" if location else ev["address"]
        desc = ev.get("description", "")
        if ev.get("host"):
            desc = f"Hosted by {ev['host']}\n\n{desc}".strip()
        if ev.get("url"):
            desc = f"{desc}\n\n{ev['url']}".strip()
        lines += [
            "BEGIN:VEVENT",
            f"UID:{ev['id']}@atihx-community-calendar",
            f"DTSTAMP:{now}",
            f"DTSTART;TZID={tz}:{local_stamp(ev['start'])}",
            f"DTEND;TZID={tz}:{local_stamp(ev['end'])}",
            f"SUMMARY:{ics_escape(ev['title'] + ' · ATIHx ' + community['short'])}",
        ]
        if location:
            lines.append(f"LOCATION:{ics_escape(location)}")
        if desc:
            lines.append(f"DESCRIPTION:{ics_escape(desc)}")
        if ev.get("url"):
            lines.append(f"URL:{ev['url']}")
        lines.append("END:VEVENT")
    lines.append("END:VCALENDAR")
    return "\r\n".join(fold(l) for l in lines) + "\r\n"


def main():
    data = json.loads(DATA.read_text(encoding="utf-8"))
    communities = {c["id"]: c for c in data["communities"]}
    events = sorted(data["events"], key=lambda e: e["start"])

    # 1. events.js for the page
    js = (
        "// Generated by scripts/build.py from data/events.json. Do not edit by hand.\n"
        "window.ATIH_DATA = " + json.dumps(data, indent=2, ensure_ascii=False) + ";\n"
    )
    (ROOT / "data" / "events.js").write_text(js, encoding="utf-8")

    # 2. calendar feeds
    CAL_DIR.mkdir(exist_ok=True)
    for old in CAL_DIR.glob("*.ics"):
        old.unlink()
    ids = sorted(communities)
    (CAL_DIR / "all.ics").write_text(
        build_ics("ATIHx Community Calendar", events, communities), encoding="utf-8"
    )
    # Combined feeds for every mix of communities while the list is small.
    # Past 5 communities that gets large, so only single-community feeds are made
    # (the page then offers one feed per selected community instead).
    max_size = len(ids) - 1 if len(ids) <= 5 else 1
    for size in range(1, max_size + 1):
        for combo in itertools.combinations(ids, size):
            subset = [e for e in events if e["community"] in combo]
            label = " + ".join(communities[c]["short"] for c in combo)
            (CAL_DIR / f"{'+'.join(combo)}.ics").write_text(
                build_ics(f"ATIHx {label}", subset, communities), encoding="utf-8"
            )
    print(f"Built data/events.js and {len(list(CAL_DIR.glob('*.ics')))} calendar feeds "
          f"from {len(events)} events.")


if __name__ == "__main__":
    main()
